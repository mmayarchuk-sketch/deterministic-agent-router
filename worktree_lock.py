#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Замок единственного писателя для рабочего дерева agent-dispatcher.

В этом каталоге работают два агента. Читать можно одновременно, писать —
только одному. Правило без механизма не работает, поэтому механизм здесь.

ГРАНИЦА, КОТОРУЮ НАДО ЗНАТЬ: замок кооперативный. Он защищает только тех, кто
соблюдает протокол и спрашивает его перед правкой. Ни git, ни редактор, ни
чужой скрипт файлом не связаны и могут написать в дерево мимо замка. Это не
недоделка, а свойство: замок делает порядок видимым и нарушение — заметным,
но запретить запись он не может.

    python3 worktree_lock.py взять --кто claude-b --зачем "правка mail_channel"
    python3 worktree_lock.py статус
    python3 worktree_lock.py отдать --кто claude-b

Замок берётся ДО правки и держится через правку, проверки и коммит.
Сам он не снимается никогда, даже застарелый: держит его агент, а не процесс,
и долгое удержание означает лишь то, что работа не закончена. Снять чужой —
отдельное решение, и принимается оно после разговора с владельцем и осмотра
дерева, а не по возрасту записи.
"""
import argparse
import json
import os
import socket
import sys
import time

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ЗАМОК = os.path.join(ЗДЕСЬ, '.worktree.lock')


def _прочитать():
    try:
        with open(ЗАМОК, encoding='utf-8') as f:
            return json.load(f)
    except FileNotFoundError:
        return None
    except (ValueError, OSError) as беда:
        return {'битый': str(беда)}


def _возраст(запись):
    try:
        return time.time() - float(запись['взят_в'])
    except (KeyError, TypeError, ValueError):
        return None


def _человечески(секунды):
    if секунды is None:
        return 'неизвестно сколько'
    if секунды < 90:
        return '%d с' % int(секунды)
    if секунды < 5400:
        return '%d мин' % int(секунды / 60)
    return '%.1f ч' % (секунды / 3600.0)


# Живость процесса здесь НЕ признак: замок берётся короткой командой, её
# процесс умирает сразу, а замок продолжает держать агент. Проверять os.kill
# было бы ровно той ошибкой, когда признак выбран по лёгкости измерения, а не
# по тому, что он означает. Поэтому pid пишется как след, но выводом не правит.


def взять(кто, зачем):
    запись = {
        'кто': кто,
        'зачем': зачем,
        'взят_в': time.time(),
        'взят_в_читаемо': time.strftime('%Y-%m-%d %H:%M:%S'),
        'pid': os.getpid(),
        'машина': socket.gethostname(),
    }
    текст = json.dumps(запись, ensure_ascii=False, indent=2)
    try:
        # O_EXCL: создание либо удаётся целиком, либо не удаётся вовсе.
        fd = os.open(ЗАМОК, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        занят = _прочитать() or {}
        print('ЗАНЯТО. Держит: %s' % занят.get('кто', 'неизвестно кто'))
        print('  зачем: %s' % занят.get('зачем', '—'))
        print('  держит уже: %s (с %s)'
              % (_человечески(_возраст(занят)), занят.get('взят_в_читаемо', '—')))
        print('  взят процессом %s на машине %s'
              % (занят.get('pid', '—'), занят.get('машина', '—')))
        print('\nНе снимай чужой замок молча: спроси владельца и посмотри дерево.')
        print('Долго держится — это повод выяснить, а не снять.')
        return 1
    with os.fdopen(fd, 'w', encoding='utf-8') as f:
        f.write(текст)
    print('Взято: %s — %s' % (кто, зачем))
    return 0


def отдать(кто, силой):
    занят = _прочитать()
    if занят is None:
        print('Замка нет — отдавать нечего.')
        return 0
    владелец = занят.get('кто')
    if владелец != кто and not силой:
        print('Замок держит не ты, а %s (%s).' % (владелец, занят.get('зачем', '—')))
        print('Держит уже %s. Снять чужой можно только осознанно: --силой.'
              % _человечески(_возраст(занят)))
        return 1
    os.remove(ЗАМОК)
    print('Отдано (%s)%s' % (владелец, ', снято силой' if владелец != кто else ''))
    return 0


def статус():
    занят = _прочитать()
    if занят is None:
        print('Свободно.')
        return 0
    if 'битый' in занят:
        print('Файл замка не читается: %s' % занят['битый'])
        print('Это само по себе повод разобраться, а не удалять файл.')
        return 2
    print('Занято: %s' % занят.get('кто', '—'))
    print('  зачем: %s' % занят.get('зачем', '—'))
    print('  держит: %s (с %s)'
          % (_человечески(_возраст(занят)), занят.get('взят_в_читаемо', '—')))
    print('  взят процессом %s на машине %s'
          % (занят.get('pid', '—'), занят.get('машина', '—')))
    return 0


def main(аргв=None):
    р = argparse.ArgumentParser(description='Замок единственного писателя.')
    под = р.add_subparsers(dest='команда', required=True)

    в = под.add_parser('взять', help='взять замок перед правкой')
    в.add_argument('--кто', required=True, help='кто берёт: claude-b, codex-astra…')
    в.add_argument('--зачем', required=True, help='что собираешься менять')

    о = под.add_parser('отдать', help='отдать замок после коммита')
    о.add_argument('--кто', required=True)
    о.add_argument('--силой', action='store_true',
                   help='снять чужой замок — только после разговора с владельцем')

    под.add_parser('статус', help='кто держит замок и сколько')

    а = р.parse_args(аргв)
    if а.команда == 'взять':
        return взять(а.кто, а.зачем)
    if а.команда == 'отдать':
        return отдать(а.кто, а.силой)
    return статус()


if __name__ == '__main__':
    sys.exit(main())
